function toIdentifier(value) {
  return String(value || '')
    .trim()
    .toLowerCase()
    .replace(/[’']/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

function humanizeIdentifier(value) {
  return String(value || '')
    .replace(/-/g, ' ')
    .replace(/\b\w/g, (character) => character.toUpperCase())
}

export function translateMoveName(name) {
  if (!name) return ''
  return MOVE_NAMES_ZH[toIdentifier(name)] || humanizeIdentifier(name)
}

export function translateAbilityName(name) {
  if (!name) return ''
  return ABILITY_NAMES_ZH[toIdentifier(name)] || humanizeIdentifier(name)
}

export function translateTypeName(type) {
  if (!type) return ''
  const key = toIdentifier(type)
  return TYPE_NAMES_ZH[key] || humanizeIdentifier(type)
}

export function translateEggGroupName(group) {
  if (!group) return ''
  const key = toIdentifier(group).replace(/-/g, '')
  return EGG_GROUP_NAMES_ZH[key] || EGG_GROUP_NAMES_ZH[toIdentifier(group)] || humanizeIdentifier(group)
}

export function translateEncounterTerm(term) {
  if (!term) return ''
  const normalized = humanizeIdentifier(term)
  return ENCOUNTER_TERMS_ZH[term] || ENCOUNTER_TERMS_ZH[normalized] || normalized
}

export function translateRegionName(region) {
  if (!region) return ''
  return REGION_NAMES_ZH[toIdentifier(region)] || region
}

export function translateLocationName(location) {
  if (!location) return ''
  const text = String(location)
  const identifier = toIdentifier(text)
  const direct = LOCATION_NAMES_ZH[identifier] || POKEMMO_LOCATION_NAMES_ZH[identifier]
  if (direct) return direct

  const route = text.match(/(?:^|\b)route[\s-]*(\d+)\b/i)
  if (route) {
    const regionPrefix = text.match(/^(kanto|johto|hoenn|sinnoh|unova)[\s-]+/i)
    const region = regionPrefix ? `${translateRegionName(regionPrefix[1])}` : ''
    return `${region}${route[1]}号道路`
  }

  return text
}
